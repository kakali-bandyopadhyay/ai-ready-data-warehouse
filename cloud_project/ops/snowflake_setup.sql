-- Run this one-time provisioning script as ACCOUNTADMIN. The resource monitor
-- can only be created and attached to a warehouse by ACCOUNTADMIN. Ownership
-- of every demo resource is then transferred to AIRDW_ROLE for dbt and teardown.
USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS AIRDW_ROLE;

CREATE WAREHOUSE IF NOT EXISTS AI_READY_XS_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS AI_READY_DEMO;
CREATE SCHEMA IF NOT EXISTS AI_READY_DEMO.AI_READY_DEMO_RAW;

-- Resource monitors are account-plan and privilege dependent. If this fails,
-- configure a budget alert in the account UI and keep AUTO_SUSPEND enabled.
CREATE OR REPLACE RESOURCE MONITOR AI_READY_DEMO_MONITOR
  WITH CREDIT_QUOTA = 10
  FREQUENCY = MONTHLY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 80 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND;
ALTER WAREHOUSE AI_READY_XS_WH SET RESOURCE_MONITOR = AI_READY_DEMO_MONITOR;

GRANT OWNERSHIP ON DATABASE AI_READY_DEMO
  TO ROLE AIRDW_ROLE COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA AI_READY_DEMO.AI_READY_DEMO_RAW
  TO ROLE AIRDW_ROLE COPY CURRENT GRANTS;
GRANT OWNERSHIP ON WAREHOUSE AI_READY_XS_WH
  TO ROLE AIRDW_ROLE COPY CURRENT GRANTS;
GRANT OWNERSHIP ON RESOURCE MONITOR AI_READY_DEMO_MONITOR
  TO ROLE AIRDW_ROLE COPY CURRENT GRANTS;
